// Categorias que se publican durante la campaña de Navidad. El resto del
// catalogo se carga en borrador y se publica cuando termine la campaña.
export const CATEGORIAS_CAMPANA = ["Navidad", "Regalos", "Juguetes"]

export function sinTildes(texto: string) {
  return texto.normalize("NFD").replace(/[̀-ͯ]/g, "").toLowerCase()
}

// Cada palabra coincide completa, tambien en plural (reno, renos). Las que
// terminan en * coinciden como inicio de palabra (limpia* -> limpiatodo).
// Tambien acepta la cantidad pegada, como en "Arbolitox120cm".
const patron = (palabra: string) => {
  const prefijo = palabra.endsWith("*")
  const base = sinTildes(prefijo ? palabra.slice(0, -1) : palabra)
    .replace(/[.*+?^${}()|[\]\\]/g, "\\$&")
    .replace(/\s+/g, "\\s+")
  return prefijo ? base : `${base}(?:s|es)?(?=$|[^a-z0-9]|x\\d)`
}

const REGEX_REGLAS = REGLAS_CATEGORIA.map((regla) => ({
  categoria: regla.categoria,
  regex: new RegExp(`(^|[^a-z0-9])(${regla.palabras.map(patron).join("|")})`),
}))

export function categoriaDe(nombre: string) {
  const texto = sinTildes(nombre)
  return (
    REGEX_REGLAS.find((regla) => regla.regex.test(texto))?.categoria ??
    CATEGORIA_POR_DEFECTO
  )
}
